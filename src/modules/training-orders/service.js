'use strict';

/** Route/service layer for training order allocation + print.
 * Wires training-orders/index.js (business logic) to the imports router,
 * and persists the generated document bytes to the new training_orders table.
 */

const crypto = require('crypto');
const { allocateTraining, buildTrainingOrderDocx, createTrainingOrder, downloadTrainingOrder } = require('./index');

const MAX_FILE_BYTES = 15 * 1024 * 1024;

// --- INPUT VALIDATION ------------------------------------------------------

function validateAllocateBody(body) {
  if (!body || typeof body !== 'object') {
    const err = new Error('Request body is required');
    err.statusCode = 400;
    throw err;
  }
}

function validatePrintBody(body) {
  if (!body || typeof body !== 'object') {
    const err = new Error('Request body is required');
    err.statusCode = 400;
    throw err;
  }
  const hasTemplate = typeof body.file === 'string' || body.fileBuffer
    || typeof body.templateBase64 === 'string';
  if (!hasTemplate) {
    const err = new Error('template file (base64: file | fileBuffer | templateBase64) is required');
    err.statusCode = 400;
    throw err;
  }
  if (!body.trainingGroup || !['PO', 'APO'].includes(body.trainingGroup)) {
    const err = new Error('trainingGroup (PO|APO) is required');
    err.statusCode = 400;
    throw err;
  }
}

// --- ALLOCATE -------------------------------------------------------------

/** POST /api/imports/training-orders/allocate  (authority, admin) */
async function allocate(req, res) {
  try {
    validateAllocateBody(req.body);
    const result = await allocateTraining({ createdBy: req.session.user.id });
    res.json({ ok: true, batches: result.batches, errors: result.errors });
  } catch (err) {
    const status = err.statusCode || 500;
    if (status >= 500) console.error('allocate training failed:', err);
    res.status(status).json({ ok: false, error: status >= 500 ? 'Allocation failed' : err.message });
  }
}

// --- PRINT (BUILD + STORE) ------------------------------------------------

/** POST /api/imports/training-orders/print  (admin) */
async function printOrder(req, res) {
  try {
    validatePrintBody(req.body);
    const { file, fileBuffer, templateBase64, trainingGroup, batchId, mandal, venue, dateTime, scheduledAt, designatedOfficers, totalOfficers } = req.body;

    // 1) Build document bytes from the uploaded template + order payload.
    let templateBytes;
    if (file) {
      templateBytes = Buffer.from(file, 'base64');
    } else if (typeof templateBase64 === 'string') {
      templateBytes = Buffer.from(templateBase64, 'base64');
    } else if (fileBuffer) {
      templateBytes = fileBuffer;
    } else {
      const err = new Error('template file (base64) required');
      err.statusCode = 400;
      throw err;
    }

    const order = {
      order_id: `TR-${Date.now()}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`,
      trainingGroup,
      batchId: batchId || null,
      mandal: mandal || null,
      venue: venue || null,
      date_time: dateTime || null,
      scheduled_at: scheduledAt || null,
      designated_officers: designatedOfficers,
      total_officers: totalOfficers,
      prepared_by: req.session.user?.username || 'admin',
    };

    const docxBuffer = await buildTrainingOrderDocx(templateBytes, order);

    // 2) Persist the order + generated bytes to training_orders.
    const created = await createTrainingOrder({
      orderId: order.order_id,
      trainingGroup,
      batchId,
      mandal,
      venue,
      dateTime,
      scheduledAt,
      designatedOfficers,
      totalOfficers,
      orderPdfBuffer: null,
      orderDocxBuffer: docxBuffer,
      createdBy: req.session.user?.id,
    });

    res.json({
      ok: true,
      order: created.order,
      document: {
        docx_bytes: docxBuffer.length,
        docx_preview: docxBuffer.slice(0, 4).toString('base64'),
      },
    });
  } catch (err) {
    if (err.statusCode === 400) return res.status(400).json({ ok: false, error: err.message });
    console.error('create training order failed:', err);
    res.status(500).json({ ok: false, error: 'Failed to create training order' });
  }
}

// --- DOWNLOAD -------------------------------------------------------------

/** GET /api/imports/training-orders/:id/download  (staff+ / admin) */
async function download(req, res) {
  try {
    const { id } = req.params;
    if (!id || isNaN(Number(id))) {
      return res.status(400).json({ ok: false, error: 'id is required' });
    }
    const { order, buffer, mime } = await downloadTrainingOrder(Number(id));
    res.setHeader('Content-Type', mime);
    res.setHeader('Content-Disposition', `attachment; filename="TR-${order.order_id}.docx"`);
    res.send(buffer);
  } catch (err) {
    if (err.statusCode === 404) return res.status(404).json({ ok: false, error: err.message });
    console.error('download training order failed:', err);
    res.status(500).json({ ok: false, error: 'Failed to download' });
  }
}

module.exports = {
  allocate,
  printOrder,
  download,
};
